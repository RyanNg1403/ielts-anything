import { chromium } from "playwright-core";
const CHROME = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const [search, rest, prefix] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await page.goto("http://127.0.0.1:5173/#/", { waitUntil: "networkidle" });
await page.evaluate(() => document.fonts.ready);
const box = page.getByLabel("What do you want to practise?");
await box.click();
await page.keyboard.type(`@${search}`);
await page.waitForTimeout(500);
await page.screenshot({ path: `.shots/${prefix}-1-picker.png` });
await page.keyboard.press("Enter");
await page.keyboard.type(rest);
await page.screenshot({ path: `.shots/${prefix}-2-typed.png` });
await page.keyboard.press("Enter");
const t0 = Date.now();
await page.waitForTimeout(12000);
await page.screenshot({ path: `.shots/${prefix}-3-working.png` });
await page.getByRole("button", { name: "Send" }).waitFor({ timeout: 600000 });
console.log(`turn ${Math.round((Date.now() - t0) / 1000)}s`);
await page.waitForTimeout(1500);
await page.screenshot({ path: `.shots/${prefix}-4-done.png` });
await page.getByRole("button", { name: /^Worked/ }).first().click();
await page.waitForTimeout(500);
await page.locator("ol").first().evaluate((el) => el.scrollIntoView({ block: "center" }));
await page.screenshot({ path: `.shots/${prefix}-5-log-open.png` });
await browser.close();
