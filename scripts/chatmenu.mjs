import { chromium } from "playwright-core";
const CHROME = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const browser = await chromium.launch({ executablePath: CHROME, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await page.goto("http://127.0.0.1:5173/#/tests", { waitUntil: "networkidle" });
await page.evaluate(() => document.fonts.ready);
const row = page.getByRole("button", { name: /^Before anything else/ });
await row.hover();
await page.getByRole("button", { name: /^Options for Before anything else/ }).click();
await page.screenshot({ path: ".shots/m2-10-chat-menu.png" });
await page.getByRole("menuitem", { name: "Rename" }).click();
await page.getByLabel("Chat name").fill("Web search check");
await page.keyboard.press("Enter");
await page.waitForTimeout(800);
await page.screenshot({ path: ".shots/m2-11-renamed.png" });
await page.getByRole("button", { name: "Web search check" }).hover();
await page.getByRole("button", { name: "Options for Web search check" }).click();
await page.getByRole("menuitem", { name: "Delete" }).click();
await page.screenshot({ path: ".shots/m2-12-delete-confirm.png" });
await page.getByRole("alertdialog").getByRole("button", { name: "Delete" }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: ".shots/m2-13-deleted.png" });
console.log("remaining:", await page.getByRole("button", { name: "Web search check" }).count());
await browser.close();
